    private static func lookup(_ key: String, language: String) -> String {
        if language.hasPrefix("th"), let value = th[key] { return value }
        if language.hasPrefix("fr"), let value = fr[key] { return value }
        return en[key] ?? key
    }
    /// Tests compare the tables; a missing key shows as a raw key in the UI.
    static func strings(for language: String) -> [String: String] {
        if language.hasPrefix("fr") { return fr }
        if language.hasPrefix("th") { return th }
        return en
    }

    static func tr(_ key: String) -> String {
        if let o = override { return lookup(key, language: o) }
        return lookup(key, language: Bundle.main.preferredLocalizations.first ?? "en")
    }

    static func outputPlaceholder(for languageID: String) -> String {
        let language = Locale.Language(identifier: languageID)
        if let value = outputPlaceholders[language.minimalIdentifier] { return value }
        if let code = language.languageCode?.identifier, let value = outputPlaceholders[code] { return value }
        return tr("output.placeholder")
    }

